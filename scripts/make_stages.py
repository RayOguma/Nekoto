# ステージの .wokoto を作るスクリプト（python scripts/make_stages.py）。
# 10 のステージは、共通の形（世界・空と音・雲・地面・壁・旗・ねこ・ねこの力・見た目・クリア）にそろえてあり、
# ここで、ステージごとの違い（障害物・ねこの力のはじめの値・変えられるところ）だけを書く。
# 注意：作り直すと ゲーム/ステージ/ のファイルを上書きする。手で直したステージがあるときは、先にここへ写すこと。
# ステージを足すときは、下の stages に1つ足して作り直し、src/game.test.ts の answers に答えの一例を足す。
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "ゲーム", "ステージ") + "/"
T = "\t"
OPEN = "# ▼ 変えられる"
CLOSE = "# ▲ ここまで"


def editable(lines):
    return [OPEN, *lines, CLOSE]


def ground_row(start, count):
    return [
        f"置く横 を {start} に する。",
        f"{count}回 繰り返す：",
        T + "地面 を 横 (置く横) 縦 0 から 出す。",
        T + "置く横 を 置く横 + 80 に する。",
    ]


FULL_GROUND = ground_row(0, 30)


def pit_ground(left_end, right_start):
    # left_end：左の地面の終わり（80 の倍数）。right_start：右の地面の始まり（80 の倍数）。
    return [
        "地面右端 という 地面 を 作る。",
        "地面右端 の 絵 を 「地面右端.png」 に する。",
        "地面左端 という 地面 を 作る。",
        "地面左端 の 絵 を 「地面左端.png」 に する。",
        *ground_row(0, left_end // 80 - 1),
        f"地面右端 は 横 {left_end - 80} 縦 0 に いる。",
        f"地面左端 は 横 {right_start} 縦 0 に いる。",
        *ground_row(right_start + 80, (2400 - right_start) // 80 - 1),
    ]


WALL = ["壁 という 四角 を 作る。", "壁 の 絵 を 「壁.png」 に する。", "壁 の 幅 を 80 に する。", "壁 の 高さ を 80 に する。"]


def wall_column(x, blocks):
    return ["# 壁を置く", *[f"壁 は 横 {x} 縦 {80 + 80 * i} に いる。" for i in range(blocks)]]


def wall_rows(x_from, columns, blocks):
    lines = []
    for i in range(blocks):
        lines += [
            f"置く横 を {x_from} に する。",
            f"{columns}回 繰り返す：",
            T + f"壁 を 横 (置く横) 縦 {80 + 80 * i} から 出す。",
            T + "置く横 を 置く横 + 80 に する。",
        ]
    return lines


MICE = [
    "ねずみ という 四角 を 作る。",
    "ねずみ の 絵 を 「ねずみ歩き1.png」 と 「ねずみ歩き2.png」 に する。",
    "ねずみ の 幅 を 56 に する。",
    "ねずみ の 高さ を 56 に する。",
    "ねずみ に 重力 を 1500 だけ かける。",
    "ねずみ は 地面 を 通れない。",
]


def mice(every, speed, at_x):
    # ねこの少し先に、every 秒ごとにわいて、左へ歩く。
    return [
        "# ねずみ（ねこの先から、次々わいて左へ歩く）",
        *MICE,
        *[f"ねずみ は 横 {x} 縦 80 に いる。" for x in at_x],
        f"ねずみ を {every}秒 ごと に 横 (ねこ の 横 + 700) 縦 80 から 出す。",
        "ずっと：",
        T + f"ねずみ を 左 に {speed} だけ 動かす。",
        "",
    ]


MICE_RULE = ("# ねずみに触れたら", ["ねこ が ねずみ に 触れたら、ねこ を 横 80 縦 80 に 動かす。"])


def stage(
    title,
    about,
    ground=FULL_GROUND,
    obstacles=(),
    flag=(2250, 80),
    solids="地面 と 壁",
    walk=("右", 5),
    jump=200,
    jumps=1,
    gravity=1500,
    extra_editable=(),
):
    lines = [
        f"# {title}",
        "# ねこを旗まで連れていこう。左右キーで歩き、スペースでジャンプ。",
        *[f"# {line}" for line in about],
        "# ✏ の付いた行は、自由に書き換えてよい。答えは1つじゃない。",
        "",
        "# 世界",
        "世界 の 大きさ を 横 2400 縦 450 に する。",
        "カメラ は ねこ を 追う。",
        "",
        "# 空と音",
        *editable(["背景 の 絵 を 「空.png」 に する。", "「曲.mp3」 を 何度も 鳴らす。"]),
        "",
        "# 雲",
        *editable(
            [
                "雲 という 四角 を 作る。",
                "雲 の 絵 を 「雲大.png」 に する。",
                "雲 の 幅 を 200 に する。",
                "雲 の 高さ を 100 に する。",
                "雲 は 横 150 縦 300 に いる。",
                "雲 は 横 900 縦 330 に いる。",
                "雲 は 横 1700 縦 310 に いる。",
                "小雲 という 雲 を 作る。",
                "小雲 の 絵 を 「雲小.png」 に する。",
                "小雲 の 幅 を 120 に する。",
                "小雲 の 高さ を 60 に する。",
                "小雲 は 横 550 縦 360 に いる。",
                "小雲 は 横 1300 縦 300 に いる。",
                "小雲 は 横 2100 縦 350 に いる。",
            ]
        ),
        "",
        "# 地面（80 ずつ並べる）",
        "地面 という 四角 を 作る。",
        "地面 の 絵 を 「地面.png」 に する。",
        "地面 の 幅 を 80 に する。",
        "地面 の 高さ を 80 に する。",
        *ground,
        "",
        "# 壁",
        *WALL,
        "",
        *obstacles,
        "# 世界の左右の端（見えない壁。ねこが世界の外へ出ないように）",
        "端 という 壁 を 作る。",
        "端 の 高さ を 2000 に する。",
        "端 は 横 -80 縦 0 に いる。",
        "端 は 横 2400 縦 0 に いる。",
        "",
        "# ゴール",
        "旗 という 四角 を 作る。",
        "旗 の 絵 を 「旗.png」 に する。",
        "旗 の 幅 を 60 に する。",
        "旗 の 高さ を 180 に する。",
        f"旗 は 横 {flag[0]} 縦 {flag[1]} に いる。",
        "",
        "# ねこ",
        "ねこ という 四角 を 作る。",
        "ねこ の 絵 を 「ねこ右立ち.png」 に する。",
        "ねこ は 横 80 縦 80 に いる。",
        f"ねこ は {solids} を 通れない。",
        "",
        "# ねこの力（大きさ・重さ・歩く速さ・ジャンプ）",
        *editable(
            [
                "ねこ の 幅 を 56 に する。",
                "ねこ の 高さ を 56 に する。",
                f"ねこ に 重力 を {gravity} だけ かける。",
                "ずっと：",
                T + f"右キー を 押している なら、ねこ を {walk[0]} に {walk[1]} だけ 動かす。",
                T + f"左キー を 押している なら、ねこ を 左 に {walk[1]} だけ 動かす。",
                f"スペース を 押したら、ねこ を {jump} だけ {jumps}回 まで ジャンプ させる。",
            ]
        ),
        "",
    ]
    for heading, body in extra_editable:
        lines += [heading, *editable(body), ""]
    lines += [
        "# ねこの見た目（向き・歩く・ジャンプ）",
        "顔 を 「右」 に する。",
        "空中 を 偽 に する。",
        "スペース を 押したら、空中 を 真 に する。",
        f"ねこ が {solids} に 上 から 触れたら、空中 を 偽 に する。",
        "ずっと：",
        T + "右キー を 押している なら、顔 を 「右」 に する。",
        T + "左キー を 押している なら、顔 を 「左」 に する。",
        T + "ねこ の 絵 を 「ねこ」 + 顔 + 「立ち.png」 に する。",
        T + "右キー を 押している または 左キー を 押している なら、ねこ の 絵 を (「ねこ」 + 顔 + 「歩き1.png」) と (「ねこ」 + 顔 + 「歩き2.png」) に する。",
        T + "空中 なら、ねこ の 絵 を 「ねこ」 + 顔 + 「ジャンプ.png」 に する。",
        "",
        "# 落ちたら、はじめの場所に戻る",
        "ずっと：",
        T + "ねこ の 縦 < 0 なら、ねこ を 横 80 縦 80 に 動かす。",
        "",
        "# クリア",
        "クリア を 偽 に する。",
        "ねこ が 旗 に 触れたら、クリア を 真 に する。",
        "",
        "# クリアの演出",
        *editable(
            [
                "ねこ が 旗 に 触れたら：",
                T + "音 を 止める。",
                T + "「クリア.mp3」 を 鳴らす。",
                T + "「クリア！」 を 赤 で 大きさ 64 で 書く。",
            ]
        ),
        "",
        "# 自由に書けるところ（文を足してみよう）",
        *editable([""]),
    ]
    return "\n".join(lines) + "\n"


PLATFORM = ["台 という 四角 を 作る。", "台 の 絵 を 「台.png」 に する。", "台 の 幅 を 160 に する。", "台 の 高さ を 40 に する。"]

