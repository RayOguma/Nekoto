# ステージの .wokoto を作るスクリプト（python scripts/make_stages.py）。
# 10 のステージは、共通の形（世界・空と音・雲・地面・壁・旗・ねこ・ねこの力・見た目・クリア）にそろえてあり、
# ここで、ステージごとの違い（障害物・ねこの力のはじめの値・変えられるところ）だけを書く。
# 注意：作り直すと ゲーム/ステージ/ のファイルを上書きする。手で直したステージがあるときは、先にここへ写すこと。
# ステージを足すときは、下の stages に1つ足して作り直し、src/game.test.ts の answers に答えの一例を足す。
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "ゲーム", "ステージ") + "/"
T = "\t"
OPEN = "# ▼ 変えられる"
CLOSE = "# ▲ ここまで"


def editable(lines):
    return [OPEN, *lines, CLOSE]


def ground_row(start, count):
    return [
        f"置く横 を {start} に する。",
        f"{count}回 繰り返す：",
        T + "地面 を 横 (置く横) 縦 0 から 出す。",
        T + "置く横 を 置く横 + 80 に する。",
    ]


FULL_GROUND = ground_row(0, 30)


def pit_ground(left_end, right_start):
    # left_end：左の地面の終わり（80 の倍数）。right_start：右の地面の始まり（80 の倍数）。
    return [
        "地面右端 という 地面 を 作る。",
        "地面右端 の 絵 を 「地面右端.png」 に する。",
        "地面左端 という 地面 を 作る。",
        "地面左端 の 絵 を 「地面左端.png」 に する。",
        *ground_row(0, left_end // 80 - 1),
        f"地面右端 は 横 {left_end - 80} 縦 0 に いる。",
        f"地面左端 は 横 {right_start} 縦 0 に いる。",
        *ground_row(right_start + 80, (2400 - right_start) // 80 - 1),
    ]


WALL = ["壁 という 四角 を 作る。", "壁 の 絵 を 「壁.png」 に する。", "壁 の 幅 を 80 に する。", "壁 の 高さ を 80 に する。"]


def wall_column(x, blocks):
    return ["# 壁を置く", *[f"壁 は 横 {x} 縦 {80 + 80 * i} に いる。" for i in range(blocks)]]


def wall_rows(x_from, columns, blocks):
    lines = []
    for i in range(blocks):
        lines += [
            f"置く横 を {x_from} に する。",
            f"{columns}回 繰り返す：",
            T + f"壁 を 横 (置く横) 縦 {80 + 80 * i} から 出す。",
            T + "置く横 を 置く横 + 80 に する。",
        ]
    return lines


MICE = [
    "ねずみ という 四角 を 作る。",
    "ねずみ の 絵 を 「ねずみ歩き1.png」 と 「ねずみ歩き2.png」 に する。",
    "ねずみ の 幅 を 56 に する。",
    "ねずみ の 高さ を 56 に する。",
    "ねずみ に 重力 を 1500 だけ かける。",
    "ねずみ は 地面 を 通れない。",
]


def mice(every, speed, at_x):
    # ねこの少し先に、every 秒ごとにわいて、左へ歩く。
    return [
        "# ねずみ（ねこの先から、次々わいて左へ歩く）",
        *MICE,
        *[f"ねずみ は 横 {x} 縦 80 に いる。" for x in at_x],
        f"ねずみ を {every}秒 ごと に 横 (ねこ の 横 + 700) 縦 80 から 出す。",
        "ずっと：",
        T + f"ねずみ を 左 に {speed} だけ 動かす。",
        "",
    ]


MICE_RULE = ("# ねずみに触れたら", ["ねこ が ねずみ に 触れたら、ねこ を 横 80 縦 80 に 動かす。"])


