def block_rows(x_from, columns, ys):
    # 壁のブロックを、横に columns 個、縦の位置 ys ごとに並べる。
    lines = []
    for y in ys:
        lines += [
            f"置く横 を {x_from} に する。",
            f"{columns}回 繰り返す：",
            T + f"壁 を 横 (置く横) 縦 {y} から 出す。",
            T + "置く横 を 置く横 + 80 に する。",
        ]
    return lines


